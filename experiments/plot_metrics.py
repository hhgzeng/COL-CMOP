"""Generate metric-comparison charts from a CSV report.

This replaces the former result-directory-specific plotting scripts.  It can
read either ``full_stat_summary.csv`` or the CSV generated by
``analyze_ranks.py`` and writes all figures to ``--output-dir``.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from experiments.analysis_utils import (  # noqa: E402
    ABLATION_ALGORITHMS,
    ALGORITHM_LABELS,
    DEFAULT_RESULTS_DIR,
    MAIN_ALGORITHMS,
    PROBLEMS_INFO,
)

plt.rcParams["font.sans-serif"] = ["DejaVu Sans", "Arial", "Helvetica", "SimHei", "STHeiti"]
plt.rcParams["axes.unicode_minus"] = False

COLORS = {
    "DSOCOL": "#3B82F6",
    "APSEA": "#94A3B8",
    "CMOCSO": "#0D9488",
    "IMCMOEAD": "#CBD5E1",
    "DSOCOL1": "#F59E0B",
    "DSOCOL3": "#10B981",
    "DSOCOL4": "#8B5CF6",
}
EDGE_COLORS = {
    "DSOCOL": "#1D4ED8",
    "APSEA": "#64748B",
    "CMOCSO": "#0F766E",
    "IMCMOEAD": "#94A3B8",
    "DSOCOL1": "#D97706",
    "DSOCOL3": "#059669",
    "DSOCOL4": "#7C3AED",
}
HATCHES = {
    "DSOCOL": "///",
    "APSEA": "",
    "CMOCSO": "..",
    "IMCMOEAD": "",
    "DSOCOL1": "..",
    "DSOCOL3": "\\\\\\",
    "DSOCOL4": "xx",
}
FALLBACK_COLORS = ["#64748B", "#0D9488", "#F59E0B", "#8B5CF6", "#10B981"]


def load_metrics(input_dir: Path, input_file: Path | None) -> tuple[pd.DataFrame, Path]:
    if input_file:
        path = input_file
        if not path.is_absolute():
            path = input_dir / path
    else:
        candidates = [
            input_dir / "full_stat_summary.csv",
            input_dir / "per_problem_metrics_detail.csv",
        ]
        path = next((candidate for candidate in candidates if candidate.exists()), None)
        if path is None:
            raise FileNotFoundError(
                f"在 {input_dir} 中未找到 full_stat_summary.csv 或 "
                "per_problem_metrics_detail.csv；也可以使用 --input-file 指定。"
            )

    frame = pd.read_csv(path)
    frame.columns = [str(column).strip() for column in frame.columns]
    for column in ["Category", "Problem", "Algorithm", "Label"]:
        if column in frame:
            frame[column] = frame[column].astype(str).str.strip()
    required = {"Problem", "Algorithm", "IGD_Mean", "HV_Mean"}
    missing = required.difference(frame.columns)
    if missing:
        raise ValueError(f"指标 CSV 缺少列: {sorted(missing)}")
    for column in ["IGD_Mean", "IGD_Std", "HV_Mean", "HV_Std"]:
        if column in frame:
            numeric = np.asarray(pd.to_numeric(frame[column], errors="coerce"), dtype=float)
            frame[column] = np.nan_to_num(numeric, nan=0.0)
    if "IGD_Std" not in frame:
        frame["IGD_Std"] = 0.0
    if "HV_Std" not in frame:
        frame["HV_Std"] = 0.0
    return frame, path


def select_algorithms(frame: pd.DataFrame, requested: list[str] | None) -> list[str]:
    available = list(dict.fromkeys(frame["Algorithm"].tolist()))
    if requested:
        missing = [algorithm for algorithm in requested if algorithm not in available]
        if missing:
            raise ValueError(f"指标 CSV 中不存在算法: {missing}")
        return requested
    preferred = ABLATION_ALGORITHMS if set(ABLATION_ALGORITHMS) <= set(available) else MAIN_ALGORITHMS
    selected = [algorithm for algorithm in preferred if algorithm in available]
    return selected or available


def style_for(algorithm: str, index: int) -> tuple[str, str, str, str]:
    return (
        COLORS.get(algorithm, FALLBACK_COLORS[index % len(FALLBACK_COLORS)]),
        EDGE_COLORS.get(algorithm, "#334155"),
        HATCHES.get(algorithm, ""),
        ALGORITHM_LABELS.get(algorithm, algorithm),
    )


def problem_info(frame: pd.DataFrame) -> list[dict]:
    available = set(frame["Problem"].tolist())
    selected = [item for item in PROBLEMS_INFO if item["name"] in available]
    return selected or [
        {"name": problem, "category": "", "note": ""}
        for problem in frame["Problem"].drop_duplicates().tolist()
    ]


def value(frame: Any, problem: str, algorithm: str, column: str) -> float:
    rows = frame[(frame["Problem"] == problem) & (frame["Algorithm"] == algorithm)]
    return float(rows[column].iloc[0]) if not rows.empty else 0.0


def format_value(value_: float, metric: str) -> str:
    if not np.isfinite(value_) or value_ == 0:
        return "0.000" if metric == "HV" else "0.0000"
    if value_ < 0.1:
        return f"{value_:.4f}"
    return f"{value_:.3f}"


def plot_relative_scores(
    frame: pd.DataFrame,
    problems: list[dict],
    algorithms: list[str],
    metric: str,
    output_path: Path,
) -> None:
    fig, ax = plt.subplots(figsize=(14.5, 7.8), dpi=300)
    bar_width = 0.18 if len(algorithms) <= 4 else min(0.7 / len(algorithms), 0.18)
    gap = 0.45
    positions = np.arange(len(problems)) * (len(algorithms) * bar_width + gap)
    raw = np.array(
        [
            [value(frame, item["name"], algorithm, f"{metric}_Mean") for algorithm in algorithms]
            for item in problems
        ]
    )
    scores = np.zeros_like(raw)
    for row_index, row in enumerate(raw):
        best = np.min(row) if metric == "IGD" else np.max(row)
        if best > 0:
            scores[row_index] = best / row * 100 if metric == "IGD" else row / best * 100

    for index, algorithm in enumerate(algorithms):
        color, edge, hatch, label = style_for(algorithm, index)
        offset = (index - (len(algorithms) - 1) / 2) * bar_width
        bars = ax.bar(
            positions + offset,
            scores[:, index],
            width=bar_width * 0.9,
            color=color,
            edgecolor=edge,
            hatch=hatch,
            linewidth=1.1,
            label=label,
            zorder=3,
        )
        for row_index, bar in enumerate(bars):
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                bar.get_height() + 2,
                f"{format_value(raw[row_index, index], metric)}\n({scores[row_index, index]:.1f}%)",
                ha="center",
                va="bottom",
                fontsize=8,
                fontweight="bold" if algorithm == "DSOCOL" else "normal",
            )

    ax.set_ylim(0, 122)
    ax.set_yticks([0, 20, 40, 60, 80, 100])
    ax.set_yticklabels(["0%", "20%", "40%", "60%", "80%", "100%"])
    direction = "Lower" if metric == "IGD" else "Higher"
    ax.set_ylabel(f"Relative {metric} Score (%) [100% = Best]\n{direction} raw value is better")
    ax.set_xticks(positions)
    ax.set_xticklabels(
        [f"{item['name']}\n{item.get('note', '')}" for item in problems],
        fontsize=10,
        fontweight="bold",
    )
    ax.grid(axis="y", linestyle="--", alpha=0.45, zorder=1)
    ax.set_axisbelow(True)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.02), ncol=min(4, len(algorithms)), frameon=False)
    fig.suptitle(f"Algorithm Benchmark Relative Performance: {metric}", fontweight="bold")
    fig.tight_layout(rect=(0.0, 0.03, 1.0, 0.95))
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved: {output_path}")


def plot_raw_panels(
    frame: pd.DataFrame,
    problems: list[dict],
    algorithms: list[str],
    metric: str,
    output_path: Path,
) -> None:
    fig, axes = plt.subplots(2, 3, figsize=(15, 8.8), dpi=300)
    axes = axes.flatten()
    x = np.arange(len(algorithms))
    mean_column = f"{metric}_Mean"
    std_column = f"{metric}_Std"

    for panel_index, item in enumerate(problems[: len(axes)]):
        ax = axes[panel_index]
        values = [value(frame, item["name"], algorithm, mean_column) for algorithm in algorithms]
        errors = [value(frame, item["name"], algorithm, std_column) for algorithm in algorithms]
        colors = [style_for(algorithm, index)[0] for index, algorithm in enumerate(algorithms)]
        edges = [style_for(algorithm, index)[1] for index, algorithm in enumerate(algorithms)]
        hatches = [style_for(algorithm, index)[2] for index, algorithm in enumerate(algorithms)]
        bars = ax.bar(x, values, yerr=errors, capsize=4, color=colors, edgecolor=edges, hatch=hatches, error_kw={"ecolor": "#334155"})
        for index, bar in enumerate(bars):
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                bar.get_height() + errors[index] + max(values + [0]) * 0.03,
                format_value(values[index], metric),
                ha="center",
                va="bottom",
                fontsize=8,
                fontweight="bold" if algorithms[index] == "DSOCOL" else "normal",
            )
        ax.set_title(f"{item['name']} {item.get('note', '')} ({item.get('category', '')})", fontsize=10)
        ax.set_xticks(x)
        ax.set_xticklabels([style_for(algorithm, index)[3] for index, algorithm in enumerate(algorithms)], rotation=15, fontsize=8)
        ax.grid(axis="y", linestyle="--", alpha=0.45)
        ax.set_axisbelow(True)
        max_y = max(values + errors + [1.0])
        ax.set_ylim(0, max_y * 1.3)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)

    for ax in axes[len(problems) :]:
        ax.axis("off")
    direction = "Lower" if metric == "IGD" else "Higher"
    fig.suptitle(f"Detailed Raw Metric Analysis: {metric} (Mean ± Std, {direction} is better)", fontweight="bold")
    fig.tight_layout(rect=(0.0, 0.02, 1.0, 0.95))
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved: {output_path}")


def main() -> None:
    parser = argparse.ArgumentParser(description="从指标 CSV 生成 IGD/HV 对比图。")
    parser.add_argument("--input-dir", "--results-dir", dest="input_dir", type=Path, default=DEFAULT_RESULTS_DIR, help="指标 CSV 所在目录")
    parser.add_argument("--input-file", type=Path, default=None, help="指定输入 CSV 文件名或路径")
    parser.add_argument("--output-dir", type=Path, default=None, help="图片输出目录（默认与输入目录相同）")
    parser.add_argument("--algorithms", nargs="+", default=None, help="参与绘图的算法列表")
    args = parser.parse_args()

    input_dir = args.input_dir.expanduser()
    output_dir = (args.output_dir or input_dir).expanduser()
    frame, input_path = load_metrics(input_dir, args.input_file)
    algorithms = select_algorithms(frame, args.algorithms)
    problems = problem_info(frame)
    output_dir.mkdir(parents=True, exist_ok=True)
    print(f"读取指标: {input_path}")
    print(f"算法: {algorithms}")
    for metric in ["IGD", "HV"]:
        plot_relative_scores(frame, problems, algorithms, metric, output_dir / f"{metric.lower()}_deepseek_style.png")
        plot_raw_panels(frame, problems, algorithms, metric, output_dir / f"{metric.lower()}_subplot_grid.png")


if __name__ == "__main__":
    main()
